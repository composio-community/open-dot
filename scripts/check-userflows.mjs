import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { spawn } from "node:child_process";
import { once } from "node:events";
import { DatabaseSync } from "node:sqlite";
import { _electron } from "playwright";

const root = path.resolve(import.meta.dirname, "..");
const evidence = path.join(root, ".windows-check-output/evidence");
const profile = fs.mkdtempSync(path.join(root, ".windows-check-flows-"));
const env = { ...process.env, OPEN_DOT_USER_DATA_DIR: profile, DOTS_COMPUTER: "local", OPENAI_API_KEY: "", OPENROUTER_API_KEY: "", COMPOSIO_API_KEY: "", E2B_API_KEY: "" };
delete env.ELECTRON_RUN_AS_NODE;
const exeIndex = process.argv.indexOf("--exe");
const options = exeIndex >= 0 || process.argv.includes("--packaged")
  ? { executablePath: exeIndex >= 0 ? path.resolve(process.argv[exeIndex + 1]) : path.join(root, "dist/win-unpacked/Open Dot.exe") }
  : { args: [path.join(root, "electron")] };
const result = { artifact: options.executablePath || "prepared production server", checks: [] };
let app, db, locker;
const errors = [];
const check = name => { result.checks.push(name); console.log("PASS:", name); };
const scalar = (sql, ...args) => Object.values(db.prepare(sql).get(...args))[0];
try {
  app = await _electron.launch({ ...options, env, timeout: 60_000 });
  let page = await app.firstWindow();
  page.on("pageerror", err => errors.push(err.message));
  await page.waitForURL("http://localhost:3100/**", { timeout: 60_000 });
  const create = async name => {
    await page.goto("http://localhost:3100/new");
    await page.getByPlaceholder("Pixel", { exact: true }).fill(name);
    await page.getByPlaceholder("What should it help with?").fill("Synthetic offline acceptance");
    await page.getByRole("button", { name: `Create ${name}`, exact: true }).click();
    await page.waitForURL(/\/dots\/dot_/);
    return new URL(page.url()).pathname.split("/").pop();
  };
  const first = await create("Flow one");
  const second = await create("Flow two");
  const third = await create("Flow three");
  db = new DatabaseSync(path.join(profile, "data/dots.db"), { readOnly: true });
  assert.equal(scalar("SELECT count(*) FROM dots"), 3);
  await page.locator(`aside a[href='/dots/${first}']`).click();
  await page.getByRole("heading", { name: "Hi, I'm Flow one", exact: true }).waitFor();
  await page.getByRole("link", { name: "Setup: rules, routines, memory, skills", exact: true }).click();
  await page.getByLabel("Name", { exact: true }).fill("Renamed café 数据");
  await page.getByRole("button", { name: "Save changes", exact: true }).click();
  await page.getByRole("heading", { name: "How Renamed café 数据 works", exact: true }).waitFor();
  check("create three dots, select, rename with Unicode");

  await page.getByPlaceholder("Add something it should remember").fill("Synthetic memory that survives restart");
  await page.getByRole("button", { name: "Add", exact: true }).click();
  await page.getByText("Synthetic memory that survives restart", { exact: true }).waitFor();
  const rules = page.locator("section").filter({ has: page.getByRole("heading", { name: "Rules", exact: true }) });
  await rules.getByPlaceholder("reply to emails for me").fill("send synthetic mail");
  await rules.getByRole("button", { name: "Never allow", exact: true }).click();
  await rules.getByRole("button", { name: "Add rule", exact: true }).click();
  await rules.getByText("send synthetic mail", { exact: true }).waitFor();
  assert.equal(scalar("SELECT decision FROM rules WHERE dot_id = ?", first), "never");
  await page.getByPlaceholder("Name", { exact: true }).fill("Offline routine");
  await page.getByPlaceholder("What to do each time").fill("Synthetic routine; do not call a provider");
  await page.getByLabel("Cron schedule").fill("invalid cron");
  await page.getByRole("button", { name: "Add routine", exact: true }).click();
  await page.getByText("That schedule isn't a valid cron expression.", { exact: true }).waitFor();
  await page.getByLabel("Cron schedule").fill("0 0 1 1 *");
  await page.getByRole("button", { name: "Add routine", exact: true }).click();
  await page.getByText("Offline routine", { exact: true }).waitFor();
  const routine = page.locator("div.flex.items-start").filter({ has: page.getByText("Offline routine", { exact: true }) });
  await routine.getByRole("button", { name: "Pause", exact: true }).click();
  await routine.getByText("Paused", { exact: true }).waitFor();
  assert.equal(scalar("SELECT enabled FROM routines WHERE dot_id = ?", first), 0);
  check("memory and never rule creation, invalid cron feedback, routine creation and pause");

  await page.goto(`http://localhost:3100/dots/${first}?c=new`);
  const uploadedResponse = page.waitForResponse(r => r.url().endsWith(`/api/dots/${first}/files`) && r.request().method() === "POST");
  await page.locator('input[type="file"]').setInputFiles({ name: "flow café.txt", mimeType: "text/plain", buffer: Buffer.from("synthetic UI attachment") });
  const upload = await uploadedResponse;
  assert.equal(upload.status(), 200);
  const attachment = (await upload.json()).files[0];
  await page.getByRole("button", { name: "Remove flow café.txt", exact: true }).waitFor();
  await page.getByPlaceholder("Message Renamed café 数据…").fill("First offline conversation");
  await page.getByRole("button", { name: "Send", exact: true }).click();
  await page.waitForURL(/\?c=conv_/);
  const firstConversation = new URL(page.url()).searchParams.get("c");
  await page.getByRole("main").getByText("First offline conversation", { exact: true }).waitFor();
  await page.getByText("Something went wrong: No OpenAI API key yet. Add one in Settings.", { exact: true }).waitFor();
  const download = await page.request.get(`http://localhost:3100/api/files/${attachment.id}?download=1`);
  assert.equal(await download.text(), "synthetic UI attachment");
  assert(download.headers()["content-disposition"].startsWith("attachment;"));
  await page.locator("header").getByRole("link", { name: "New chat", exact: true }).click();
  await page.getByPlaceholder("Message Renamed café 数据…").fill("Second offline conversation");
  await page.getByRole("button", { name: "Send", exact: true }).click();
  await page.waitForURL(/\?c=conv_/);
  const secondConversation = new URL(page.url()).searchParams.get("c");
  assert.notEqual(secondConversation, firstConversation);
  await page.getByRole("main").getByText("Second offline conversation", { exact: true }).waitFor();
  await page.getByText("Something went wrong: No OpenAI API key yet. Add one in Settings.", { exact: true }).waitFor();
  const firstChat = page.locator(`aside a[href='/dots/${first}?c=${firstConversation}']`);
  await firstChat.click();
  await page.getByRole("main").getByText("First offline conversation", { exact: true }).waitFor();
  assert.equal(await page.getByRole("main").getByText("Second offline conversation", { exact: true }).count(), 0);
  const firstRow = firstChat.locator("..");
  await firstRow.hover();
  await firstRow.getByRole("button", { name: /^Delete / }).click();
  await page.locator("aside").getByRole("button", { name: "Delete", exact: true }).click();
  await page.waitForURL(`http://localhost:3100/dots/${first}`);
  await firstChat.waitFor({ state: "detached" });
  assert.equal(scalar("SELECT count(*) FROM conversations WHERE id = ?", firstConversation), 0);
  assert.equal(scalar("SELECT count(*) FROM conversations WHERE id = ?", secondConversation), 1);
  check("UI upload, attachment download, separate chats, missing-key feedback, chat selection and deletion");

  await page.goto("http://localhost:3100/channels/new");
  await page.getByPlaceholder("launch-plan", { exact: true }).fill("flow-team");
  await page.getByRole("button", { name: /Renamed café 数据 Synthetic offline acceptance/ }).click();
  await page.getByRole("button", { name: /Flow two Synthetic offline acceptance/ }).click();
  await page.getByRole("button", { name: "Make lead", exact: true }).click();
  await page.getByRole("button", { name: /Flow two Synthetic offline acceptance/ }).click();
  await page.getByRole("button", { name: /Flow three Synthetic offline acceptance/ }).click();
  await page.getByRole("button", { name: "Create #flow-team", exact: true }).click();
  await page.waitForURL(/\/channels\/ch_/);
  const channel = new URL(page.url()).pathname.split("/").pop();
  await page.getByText("2 dots · led by Renamed café 数据", { exact: true }).waitFor();
  assert.deepEqual(JSON.parse(scalar("SELECT members FROM channels WHERE id = ?", channel)).sort(), [first, third].sort());
  await page.getByRole("button", { name: "Delete channel", exact: true }).click();
  await page.locator("header").getByRole("button", { name: "Cancel", exact: true }).click();
  assert.equal(scalar("SELECT count(*) FROM channels WHERE id = ?", channel), 1);
  await page.getByRole("button", { name: "Delete channel", exact: true }).click();
  await page.locator("header").getByRole("button", { name: "Delete", exact: true }).click();
  await page.waitForURL("http://localhost:3100/");
  assert.equal(scalar("SELECT count(*) FROM channels WHERE id = ?", channel), 0);
  check("channel lead deselection, membership, deletion cancel and confirm");

  await page.goto(`http://localhost:3100/dots/${second}`);
  const lockUpload = await page.request.post(`http://localhost:3100/api/dots/${second}/files`, { multipart: { file: { name: "locked.txt", mimeType: "text/plain", buffer: Buffer.from("synthetic locked attachment") } } });
  assert.equal(lockUpload.status(), 200);
  const lockFile = (await lockUpload.json()).files[0];
  const canonical = path.join(profile, "data/files", lockFile.id);
  locker = spawn("powershell.exe", ["-NoProfile", "-NonInteractive", "-Command", "$held = [IO.File]::Open($env:OPEN_DOT_LOCK_FIXTURE, 'Open', 'Read', 'None'); [Console]::WriteLine('LOCKED'); [Console]::ReadLine() | Out-Null; $held.Dispose()"], { env: { ...env, OPEN_DOT_LOCK_FIXTURE: canonical }, windowsHide: true, stdio: ["pipe", "pipe", "pipe"] });
  await new Promise((resolve, reject) => {
    let output = "";
    locker.stdout.on("data", data => { output += data; if (output.includes("LOCKED")) resolve(); });
    locker.on("error", reject);
    locker.on("exit", code => { if (!output.includes("LOCKED")) reject(new Error(`Locker exited ${code}`)); });
  });
  await page.getByRole("link", { name: "Setup: rules, routines, memory, skills", exact: true }).click();
  await page.getByRole("button", { name: "Delete Flow two…", exact: true }).click();
  await page.getByRole("button", { name: "Yes, delete Flow two", exact: true }).click();
  await page.getByRole("alert").getByText("Could not finish deleting this dot. Close any app using its files and try again.", { exact: true }).waitFor();
  assert.equal(scalar("SELECT count(*) FROM dots WHERE id = ?", second), 1);
  assert.equal(scalar("SELECT count(*) FROM files WHERE id = ?", lockFile.id), 1);
  assert(fs.existsSync(canonical));
  assert(fs.existsSync(path.join(profile, "data/dots", second, "workspace/uploads/locked.txt")));
  const released = once(locker, "exit");
  locker.stdin.end("\n");
  await released;
  locker = null;
  await page.getByRole("button", { name: "Yes, delete Flow two", exact: true }).click();
  await page.waitForURL("http://localhost:3100/");
  assert.equal(scalar("SELECT count(*) FROM dots WHERE id = ?", second), 0);
  assert.equal(scalar("SELECT count(*) FROM files WHERE dot_id = ?", second), 0);
  assert(!fs.existsSync(canonical));
  assert(!fs.existsSync(path.join(profile, "data/dots", second)));
  check("actual Windows locked-file deletion error retains data; retry removes files and dot");

  db.close(); db = null;
  await app.close(); app = null;
  app = await _electron.launch({ ...options, env, timeout: 60_000 });
  page = await app.firstWindow();
  page.on("pageerror", err => errors.push(err.message));
  await page.waitForURL("http://localhost:3100/**", { timeout: 60_000 });
  await page.goto(`http://localhost:3100/dots/${first}?tab=setup`);
  await page.getByText("Synthetic memory that survives restart", { exact: true }).waitFor();
  await page.getByText("send synthetic mail", { exact: true }).waitFor();
  await page.getByText("Offline routine", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Forget", exact: true }).click();
  await page.getByText("Synthetic memory that survives restart", { exact: true }).waitFor({ state: "detached" });
  await page.getByRole("button", { name: "Delete rule", exact: true }).click();
  await page.getByText("send synthetic mail", { exact: true }).waitFor({ state: "detached" });
  await page.getByRole("button", { name: "Delete routine", exact: true }).click();
  await page.getByText("Offline routine", { exact: true }).waitFor({ state: "detached" });
  await page.getByRole("link", { name: "Back to chat", exact: true }).click();
  await page.getByRole("button", { name: "Pause", exact: true }).click();
  await page.getByText(/is paused\. Any ongoing work was stopped/).waitFor();
  await page.locator("header").getByRole("button", { name: "Resume", exact: true }).click();
  await page.getByPlaceholder("Message Renamed café 数据…").waitFor();
  await page.goto(`http://localhost:3100/dots/${second}`);
  await page.getByText("This dot doesn't exist.", { exact: true }).waitFor();
  assert.deepEqual(errors, []);
  check("restart persistence, memory/rule/routine removal, dot pause/resume, deleted dot route");
  fs.mkdirSync(evidence, { recursive: true });
  fs.writeFileSync(path.join(evidence, "userflows-acceptance.json"), JSON.stringify(result, null, 2));
} finally {
  if (locker) { const released = once(locker, "exit"); locker.stdin.end("\n"); await released; }
  db?.close();
  await app?.close().catch(() => {});
  if (path.dirname(profile) !== root || fs.lstatSync(profile).isSymbolicLink()) throw new Error("Unexpected flow cleanup target");
  fs.rmSync(profile, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 });
}
